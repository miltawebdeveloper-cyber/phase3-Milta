import fs from 'node:fs';

const ROOT = 'd:/milta-web-v3/milta-web';
const names = JSON.parse(fs.readFileSync(`${ROOT}/db/icon-names.json`, 'utf8'));

// MUI exports these without the "Icon" suffix: TimerIcon -> Timer.
const exportName = (n) => n.replace(/Icon$/, '');

const imports = names
  .map((n) => `import ${n} from "@mui/icons-material/${exportName(n)}";`)
  .join('\n');

const entries = names.map((n) => `  ${n},`).join('\n');

const file = `// Icon registry — generated by scripts/extract-state-pages.mjs's output.
// Regenerate with: node scripts/gen-icon-registry.mjs
//
// Page content lives in the database, where an icon can only be stored as a NAME
// ("TimerIcon"), not as a component reference. This maps those names back to
// components for the renderer.
//
// Deep single imports ("@mui/icons-material/Timer") rather than named imports off
// the package root: the root re-exports several thousand icons, and pulling the
// map in from there defeats tree-shaking and lands the whole set in the bundle.
//
// ${names.length} icons, every one of them actually used by an extracted page.

${imports}

export const ICONS = {
${entries}
};

// Accepts either a component (the pre-migration source files pass one directly)
// or a name (what the CMS stores). Returns null for anything unknown, so an
// unrecognised icon renders nothing instead of crashing the page — a missing
// 22px glyph is not worth a white screen.
export function resolveIcon(icon) {
  if (!icon) return null;
  if (typeof icon === "string") return ICONS[icon] ?? null;
  return icon;
}

export default ICONS;
`;

fs.writeFileSync(`${ROOT}/src/states/_iconRegistry.js`, file);
console.log(`wrote src/states/_iconRegistry.js with ${names.length} icons`);
