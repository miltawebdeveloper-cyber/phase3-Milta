// Split the one service-templates blob into one file per service.
//
//   node scripts/split-service-templates.mjs
//
// Eight services shared a single 20 KB JSON object, which made the templates
// hard to read and impossible to change one at a time — every edit touched the
// same file, and a diff never told you which service moved. One file per service
// makes "the Bookkeeping template" a thing you can open, read and edit on its
// own, which is the point of having eight of them.
//
// db/templates/index.json is the link between them: it maps each service name to
// its file, so the loader and the CMS enumerate services from one place rather
// than from a directory listing.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = 'd:/milta-web-v3/milta-web';
const SOURCE = path.join(ROOT, 'db/service-templates.json');
const OUT_DIR = path.join(ROOT, 'db/templates');

const slugOf = (service) =>
  String(service).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const templates = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));

fs.mkdirSync(OUT_DIR, { recursive: true });

const index = [];

for (const [service, template] of Object.entries(templates)) {
  const slug = slugOf(service);
  const file = `${slug}.json`;

  // `service` is written into the file as well as into the index, so a template
  // read on its own still knows what it is for.
  const body = { service, ...template };
  fs.writeFileSync(path.join(OUT_DIR, file), `${JSON.stringify(body, null, 2)}\n`);

  index.push({
    service,
    slug,
    file,
    sections: (template.sections || []).length,
    faqs: template.faqs || 0,
  });
}

index.sort((a, b) => a.service.localeCompare(b.service));

fs.writeFileSync(
  path.join(OUT_DIR, 'index.json'),
  `${JSON.stringify({
    note: 'One template per service. Generated by scripts/gen-service-templates.mjs; split by scripts/split-service-templates.mjs. Edit a service file, not this index.',
    templates: index,
  }, null, 2)}\n`,
);

console.log(`Wrote ${index.length} template(s) to db/templates/`);
for (const t of index) {
  console.log(`  ${t.service.padEnd(22)} ${t.file.padEnd(24)} ${String(t.sections).padStart(2)} sections, ${t.faqs} faqs`);
}
